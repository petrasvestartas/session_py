class TpmsType(IntEnum):
    GYROID = 0
    SCHWARZ_P = 1
    DIAMOND = 2
    NEOVIUS = 3
    IWP = 4
    LIDINOID = 5
    FISCHER_KOCH_S = 6
    FRD = 7
    PMY = 8


class TpmsMode(IntEnum):
    SOLID = 0
    SHEET = 1
    SHELL = 2


def _marching_cubes(fn, box, nx, ny, nz, isovalue):
    from session_py import Mesh
    from session_py import Point
    mn = box.min_point()
    mx = box.max_point()
    min_x, min_y, min_z = mn[0], mn[1], mn[2]
    dx = (mx[0] - min_x) / nx
    dy = (mx[1] - min_y) / ny
    dz = (mx[2] - min_z) / nz
    h = min(dx, dy, dz) * 0.5
    nxg, nyg, nzg = nx + 1, ny + 1, nz + 1
    field = [0.0] * (nxg * nyg * nzg)
    for i in range(nxg):
        for j in range(nyg):
            for k in range(nzg):
                field[i * nyg * nzg + j * nzg + k] = fn(
                    min_x + i * dx, min_y + j * dy, min_z + k * dz)
    edge_x = [-1] * (nx * nyg * nzg)
    edge_y = [-1] * (nxg * ny * nzg)
    edge_z = [-1] * (nxg * nyg * nz)
    mesh = Mesh()

    def get_slot(ei, ej, ek, arr, stride0, stride1):
        return ei * stride0 + ej * stride1 + ek

    def make_vertex(e, i, j, k, pt, val):
        if e == 0:
            idx = i * nyg * nzg + j * nzg + k
            arr = edge_x
        elif e == 1:
            idx = (i + 1) * ny * nzg + j * nzg + k
            arr = edge_y
        elif e == 2:
            idx = i * nyg * nzg + (j + 1) * nzg + k
            arr = edge_x
        elif e == 3:
            idx = i * ny * nzg + j * nzg + k
            arr = edge_y
        elif e == 4:
            idx = i * nyg * nzg + j * nzg + (k + 1)
            arr = edge_x
        elif e == 5:
            idx = (i + 1) * ny * nzg + j * nzg + (k + 1)
            arr = edge_y
        elif e == 6:
            idx = i * nyg * nzg + (j + 1) * nzg + (k + 1)
            arr = edge_x
        elif e == 7:
            idx = i * ny * nzg + j * nzg + (k + 1)
            arr = edge_y
        elif e == 8:
            idx = i * nyg * nz + j * nz + k
            arr = edge_z
        elif e == 9:
            idx = (i + 1) * nyg * nz + j * nz + k
            arr = edge_z
        elif e == 10:
            idx = (i + 1) * nyg * nz + (j + 1) * nz + k
            arr = edge_z
        else:
            idx = i * nyg * nz + (j + 1) * nz + k
            arr = edge_z
        if arr[idx] >= 0:
            return arr[idx]
        ca, cb = _EDGE_VERTICES[e]
        va, vb = val[ca], val[cb]
        t = 0.5 if abs(vb - va) < 1e-12 else (isovalue - va) / (vb - va)
        px = pt[ca][0] + t * (pt[cb][0] - pt[ca][0])
        py = pt[ca][1] + t * (pt[cb][1] - pt[ca][1])
        pz = pt[ca][2] + t * (pt[cb][2] - pt[ca][2])
        gnx = fn(px + h, py, pz) - fn(px - h, py, pz)
        gny = fn(px, py + h, pz) - fn(px, py - h, pz)
        gnz = fn(px, py, pz + h) - fn(px, py, pz - h)
        gl = math.sqrt(gnx*gnx + gny*gny + gnz*gnz)
        if gl > 1e-12:
            gnx /= gl; gny /= gl; gnz /= gl
        vk = mesh.add_vertex(Point(px, py, pz))
        mesh.vertex[vk].set_normal(gnx, gny, gnz)
        arr[idx] = vk
        return vk

    for i in range(nx):
        for j in range(ny):
            for k in range(nz):
                pt = [
                    (min_x + i * dx,       min_y + j * dy,       min_z + k * dz),
                    (min_x + (i+1) * dx,   min_y + j * dy,       min_z + k * dz),
                    (min_x + (i+1) * dx,   min_y + (j+1) * dy,   min_z + k * dz),
                    (min_x + i * dx,       min_y + (j+1) * dy,   min_z + k * dz),
                    (min_x + i * dx,       min_y + j * dy,       min_z + (k+1) * dz),
                    (min_x + (i+1) * dx,   min_y + j * dy,       min_z + (k+1) * dz),
                    (min_x + (i+1) * dx,   min_y + (j+1) * dy,   min_z + (k+1) * dz),
                    (min_x + i * dx,       min_y + (j+1) * dy,   min_z + (k+1) * dz),
                ]
                val = [
                    field[i * nyg * nzg + j * nzg + k],
                    field[(i+1) * nyg * nzg + j * nzg + k],
                    field[(i+1) * nyg * nzg + (j+1) * nzg + k],
                    field[i * nyg * nzg + (j+1) * nzg + k],
                    field[i * nyg * nzg + j * nzg + (k+1)],
                    field[(i+1) * nyg * nzg + j * nzg + (k+1)],
                    field[(i+1) * nyg * nzg + (j+1) * nzg + (k+1)],
                    field[i * nyg * nzg + (j+1) * nzg + (k+1)],
                ]
                cube_idx = 0
                for v in range(8):
                    if val[v] < isovalue:
                        cube_idx |= (1 << v)
                if cube_idx == 0 or cube_idx == 255:
                    continue
                tris = _TRI_TABLE[cube_idx]
                t = 0
                while t < 15:
                    if tris[t] == -1:
                        break
                    v0 = make_vertex(tris[t],     i, j, k, pt, val)
                    v1 = make_vertex(tris[t + 1], i, j, k, pt, val)
                    v2 = make_vertex(tris[t + 2], i, j, k, pt, val)
                    if v0 >= 0 and v1 >= 0 and v2 >= 0:
                        mesh.add_face([v0, v2, v1])
                    t += 3
    mesh.halfedge.clear()
    mesh.clear_pointcolors()
    mesh.clear_facecolors()
    mesh.clear_linecolors()
    return mesh


class MeshIso:
    @staticmethod
    def eval(tpms_type, x, y, z, period=1.0):
        X = x / period
        Y = y / period
        Z = z / period
        t = tpms_type
        if t == TpmsType.GYROID:
            return math.sin(X)*math.cos(Y) + math.sin(Y)*math.cos(Z) + math.sin(Z)*math.cos(X)
        elif t == TpmsType.SCHWARZ_P:
            return math.cos(X) + math.cos(Y) + math.cos(Z)
        elif t == TpmsType.DIAMOND:
            return (math.sin(X)*math.sin(Y)*math.sin(Z)
                  + math.sin(X)*math.cos(Y)*math.cos(Z)
                  + math.cos(X)*math.sin(Y)*math.cos(Z)
                  + math.cos(X)*math.cos(Y)*math.sin(Z))
        elif t == TpmsType.NEOVIUS:
            return 3.0*(math.cos(X)+math.cos(Y)+math.cos(Z)) + 4.0*math.cos(X)*math.cos(Y)*math.cos(Z)
        elif t == TpmsType.IWP:
            return (2.0*(math.cos(X)*math.cos(Y)+math.cos(Y)*math.cos(Z)+math.cos(Z)*math.cos(X))
                  - (math.cos(2.0*X)+math.cos(2.0*Y)+math.cos(2.0*Z)))
        elif t == TpmsType.LIDINOID:
            return (math.sin(2.0*X)*math.cos(Y)*math.sin(Z)
                  + math.sin(2.0*Y)*math.cos(Z)*math.sin(X)
                  + math.sin(2.0*Z)*math.cos(X)*math.sin(Y)
                  + math.cos(2.0*X)*math.cos(2.0*Y)
                  + math.cos(2.0*Y)*math.cos(2.0*Z)
                  + math.cos(2.0*Z)*math.cos(2.0*X))
        elif t == TpmsType.FISCHER_KOCH_S:
            return (math.cos(2.0*X)*math.sin(Y)*math.cos(Z)
                  + math.cos(2.0*Y)*math.sin(Z)*math.cos(X)
                  + math.cos(2.0*Z)*math.sin(X)*math.cos(Y))
        elif t == TpmsType.FRD:
            return (4.0*math.cos(X)*math.cos(Y)*math.cos(Z)
                  - (math.cos(2.0*X)*math.cos(2.0*Y)
                   + math.cos(2.0*Y)*math.cos(2.0*Z)
                   + math.cos(2.0*Z)*math.cos(2.0*X)))
        elif t == TpmsType.PMY:
            return (2.0*math.cos(X)*math.cos(Y)*math.cos(Z)
                  + math.sin(2.0*X)*math.sin(Y)
                  + math.sin(X)*math.sin(2.0*Z)
                  + math.sin(2.0*Y)*math.sin(Z))
        return 0.0

    @staticmethod
    def from_tpms(tpms_type, box, nx, ny, nz, isovalue=0.0, period=1.0,
                  mode=None, thickness=0.2):
        if mode is None:
            mode = TpmsMode.SOLID
        def fn(x, y, z):
            return MeshIso.eval(tpms_type, x, y, z, period / (2.0 * math.pi))
        if mode == TpmsMode.SOLID:
            return _marching_cubes(fn, box, nx, ny, nz, isovalue)
        m1 = _marching_cubes(fn, box, nx, ny, nz, isovalue - thickness)
        m2 = _marching_cubes(fn, box, nx, ny, nz, isovalue + thickness)
        return _merge_meshes(m1, m2)

    @staticmethod
    def from_function(fn, box, nx, ny, nz, isovalue=0.0):
        return _marching_cubes(fn, box, nx, ny, nz, isovalue)

    @staticmethod
    def sdf_sphere(cx, cy, cz, r, x, y, z):
        dx, dy, dz = x - cx, y - cy, z - cz
        return math.sqrt(dx*dx + dy*dy + dz*dz) - r

    @staticmethod
    def sdf_box(cx, cy, cz, hx, hy, hz, x, y, z):
        qx = abs(x - cx) - hx
        qy = abs(y - cy) - hy
        qz = abs(z - cz) - hz
        mx = max(qx, 0.0)
        my = max(qy, 0.0)
        mz = max(qz, 0.0)
        return math.sqrt(mx*mx + my*my + mz*mz) + min(max(qx, qy, qz), 0.0)

    @staticmethod
    def sdf_capsule(p0, p1, r, x, y, z):
        pax, pay, paz = x - p0[0], y - p0[1], z - p0[2]
        bax, bay, baz = p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]
        h = max(0.0, min(1.0, (pax*bax + pay*bay + paz*baz) / (bax*bax + bay*bay + baz*baz)))
        dx, dy, dz = pax - h * bax, pay - h * bay, paz - h * baz
        return math.sqrt(dx*dx + dy*dy + dz*dz) - r

    @staticmethod
    def sdf_torus(cx, cy, cz, major_r, minor_r, x, y, z):
        lx, ly, lz = x - cx, y - cy, z - cz
        q = math.sqrt(lx*lx + ly*ly) - major_r
        return math.sqrt(q*q + lz*lz) - minor_r

    @staticmethod
    def sdf_plane(nx, ny, nz, d, x, y, z):
        return nx*x + ny*y + nz*z - d

    @staticmethod
    def smooth_union(a, b, k=8.0):
        return -math.log(math.exp(-k * a) + math.exp(-k * b)) / k

    @staticmethod
    def smooth_subtract(a, b, k=8.0):
        return -MeshIso.smooth_union(-a, b, k)

    @staticmethod
    def smooth_intersect(a, b, k=8.0):
        return -MeshIso.smooth_union(-a, -b, k)


def _merge_meshes(m1, m2):
    from session_py import Mesh
    v1, f1 = m1.to_vertices_and_faces()
    v2, f2 = m2.to_vertices_and_faces()
    offset = len(v1)
    verts = v1 + v2
    faces = list(f1) + [[idx + offset for idx in f] for f in f2]
    result = Mesh.from_vertices_and_faces(verts, faces)
    result.halfedge.clear()
    result.clear_pointcolors()
    result.clear_facecolors()
    result.clear_linecolors()
    return result
