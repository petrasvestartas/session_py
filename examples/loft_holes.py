"""Standalone loft-with-holes example mirroring session_cpp/example_loft_holes.cpp.

Writes session_data/example_loft_holes_py.pb — load in Rhino to inspect.
"""
from pathlib import Path
from session_py import Point, Polyline, Session
from session_py.mesh import Mesh


def pl(pts):
    return Polyline([Point(*p) for p in pts])


def main():
    session = Session("LoftHoles")
    g = session.add_group("Meshes")

    # ── plate_rect ────────────────────────────────────────────────────────
    rect_bot = [
        pl([
            ( 0,  0, 0),
            (10,  0, 0),
            (10, 10, 0),
            ( 0, 10, 0),
            ( 0,  0, 0),
        ]),
        pl([
            (3, 3, 0),
            (3, 7, 0),
            (7, 7, 0),
            (7, 3, 0),
            (3, 3, 0),
        ]),
    ]
    rect_top = [
        pl([
            ( 0,  0, 2),
            (10,  0, 2),
            (10, 10, 2),
            ( 0, 10, 2),
            ( 0,  0, 2),
        ]),
        pl([
            (3, 3, 2),
            (3, 7, 2),
            (7, 7, 2),
            (7, 3, 2),
            (3, 3, 2),
        ]),
    ]
    m_rect = Mesh.loft(rect_bot, rect_top)
    m_rect.name = "plate_rect"
    session.add_mesh(m_rect, g)

    # ── plate_annen (plate_0 from annen_corner) ───────────────────────────
    annen_bot = [
        pl([
            (2142.008, -530.170, 1172.487),
            (2142.008, -530.170, -318.768),
            (2142.008, -318.102, -318.768),
            (2142.008, -347.792, -414.110),
            (2142.008, -106.034, -414.110),
            (2142.008, -135.724, -318.768),
            (2142.008,  106.034, -318.768),
            (2142.008,   76.344, -414.110),
            (2142.008,  318.102, -414.110),
            (2142.008,  288.412, -318.768),
            (2142.008,  530.170, -318.768),
            (2142.008,  530.170, 1172.487),
            (2142.008, -530.170, 1172.487),
        ]),
        pl([
            (2142.008, 97.448,  841.097),
            (2142.008,  0.000,  841.097),
            (2142.008,  0.000, 1006.792),
            (2142.008, 97.448, 1006.792),
            (2142.008, 97.448,  841.097),
        ]),
        pl([
            (2142.008, 97.448, 178.317),
            (2142.008,  0.000, 178.317),
            (2142.008,  0.000, 344.012),
            (2142.008, 97.448, 344.012),
            (2142.008, 97.448, 178.317),
        ]),
    ]
    annen_top = [
        pl([
            (2223.416, -530.170, 1172.487),
            (2223.416, -530.170, -269.141),
            (2223.416, -318.102, -269.141),
            (2223.416, -347.792, -364.483),
            (2223.416, -106.034, -364.483),
            (2223.416, -135.724, -269.141),
            (2223.416,  106.034, -269.141),
            (2223.416,   76.344, -364.483),
            (2223.416,  318.102, -364.483),
            (2223.416,  288.412, -269.141),
            (2223.416,  530.170, -269.141),
            (2223.416,  530.170, 1172.487),
            (2223.416, -530.170, 1172.487),
        ]),
        pl([
            (2223.416, 97.448,  841.097),
            (2223.416,  0.000,  841.097),
            (2223.416,  0.000, 1006.792),
            (2223.416, 97.448, 1006.792),
            (2223.416, 97.448,  841.097),
        ]),
        pl([
            (2223.416, 97.448, 178.317),
            (2223.416,  0.000, 178.317),
            (2223.416,  0.000, 344.012),
            (2223.416, 97.448, 344.012),
            (2223.416, 97.448, 178.317),
        ]),
    ]
    m_annen = Mesh.loft(annen_bot, annen_top)
    m_annen.name = "plate_annen"
    session.add_mesh(m_annen, g)

    # ── plate_collin ──────────────────────────────────────────────────────
    col_bot = [
        pl([
            ( 0, 0, 0),
            ( 4, 0, 0),
            ( 7, 0, 0),
            (12, 0, 0),
            (12, 5, 0),
            ( 0, 5, 0),
            ( 0, 0, 0),
        ]),
    ]
    col_top = [
        pl([
            ( 0, 0, 1.5),
            ( 4, 0, 1.5),
            ( 7, 0, 1.5),
            (12, 0, 1.5),
            (12, 5, 1.5),
            ( 0, 5, 1.5),
            ( 0, 0, 1.5),
        ]),
    ]
    m_collin = Mesh.loft(col_bot, col_top)
    m_collin.name = "plate_collin"
    session.add_mesh(m_collin, g)

    base = Path(__file__).resolve().parents[2]  # .../session
    pb = base / "session_data" / "example_loft_holes_py.pb"
    session.pb_dump(str(pb))

    for m in (m_rect, m_annen, m_collin):
        print(f"{m.name}: V={len(m.vertex)} F={len(m.face)} closed={m.is_closed()}")
    print(f"wrote {pb}")


if __name__ == "__main__":
    main()
